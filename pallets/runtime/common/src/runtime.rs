        impl<LocalCall> frame_system::offchain::CreateSignedTransaction<LocalCall> for Runtime
        where
            RuntimeCall: From<LocalCall>,
        {
            fn create_signed_transaction<
                C: frame_system::offchain::AppCrypto<Self::Public, Self::Signature>,
            >(
                call: RuntimeCall,
                public: <polymesh_primitives::Signature as Verify>::Signer,
                account: polymesh_primitives::AccountId,
                nonce: polymesh_primitives::Nonce,
            ) -> Option<UncheckedExtrinsic> {
                let tip = 0;
                // take the biggest period possible.
                let period = polymesh_runtime_common::BlockHashCount::get()
                    .checked_next_power_of_two()
                    .map(|c| c / 2)
                    .unwrap_or(2) as u64;
                let current_block = System::block_number()
                    .saturated_into::<u64>()
                    // The `System::block_number` is initialized with `n+1`,
                    // so the actual block number is `n`.
                    .saturating_sub(1);
                let era = generic::Era::mortal(period, current_block);
                let tx_ext: TxExtension = (
                    (
                        frame_system::AuthorizeCall::new(),
                        frame_system::CheckNonZeroSender::new(),
                        frame_system::CheckSpecVersion::new(),
                        frame_system::CheckTxVersion::new(),
                        frame_system::CheckGenesis::new(),
                    ),
                    frame_system::CheckEra::from(era),
                    frame_system::CheckNonce::from(nonce),
                    frame_system::CheckWeight::new(),
                    polymesh_transaction_payment::ChargeTransactionPayment::from(tip),
                    pallet_permissions::StoreCallMetadata::new(),
                    frame_metadata_hash_extension::CheckMetadataHash::new(false),
                    pallet_revive::evm::tx_extension::SetOrigin::default(),
                    frame_system::WeightReclaim::new(),
                );
                let raw_payload = SignedPayload::new(call, tx_ext)
                    .map_err(|e| {
                        log::warn!("Unable to create signed payload: {:?}", e);
                    })
                    .ok()?;
                let signature = raw_payload.using_encoded(|payload| C::sign(payload, public))?;
                let address = Indices::unlookup(account);
                let (call, tx_ext, _) = raw_payload.deconstruct();
                let transaction = generic::UncheckedExtrinsic::new_signed(call, address, signature, tx_ext).into();
                Some(transaction)
            }
        }

